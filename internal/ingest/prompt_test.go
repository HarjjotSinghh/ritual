func TestIsPromptLike(t *testing.T) {
	if IsPromptLike("yes") {
		t.Fatal("a two-word ack should not read as an intent")
	}
	if !IsPromptLike("deploy the storefront theme") {
		t.Fatal("a real request should read as an intent")
	}
}

