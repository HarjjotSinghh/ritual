package ingest

import (
	"strings"
	"testing"
)

func TestCleanPromptStripsHarnessBlocks(t *testing.T) {
	in := "<system-reminder>do not mention this</system-reminder>\nFix the cart drawer"
	if got := CleanPrompt(in); got != "Fix the cart drawer" {
		t.Fatalf("CleanPrompt = %q", got)
	}
}

func TestCleanPromptHandlesNestedBlocks(t *testing.T) {
	// A <rules> block contains <context> subsections. A non-greedy pattern
	// would stop at the inner closing tag and leave the outer tail behind.
	in := "<rules><context>stuff</context>more rules</rules>\nwhat should we build?"
	got := CleanPrompt(in)
	if strings.Contains(got, "rules") || strings.Contains(got, "stuff") {
		t.Fatalf("CleanPrompt left harness content: %q", got)
	}
	if got != "what should we build?" {
		t.Fatalf("CleanPrompt = %q", got)
	}
}

func TestCleanPromptDropsUnclosedBlock(t *testing.T) {
	in := "<environment_details>truncated dump that never closes"
	if got := CleanPrompt(in); got != "" {
		t.Fatalf("CleanPrompt = %q, want empty for a truncated dump", got)
	}
}

func TestCleanPromptUnwrapsUserQuery(t *testing.T) {
	in := "<timestamp>Tue</timestamp>\n<user_query>\nupdate the hero copy\n</user_query>"
	if got := CleanPrompt(in); got != "update the hero copy" {
		t.Fatalf("CleanPrompt = %q", got)
	}
}

func TestCleanPromptRejectsSyntheticRecords(t *testing.T) {
	in := "Caveat: The messages below were generated by the user while running local commands."
	if got := CleanPrompt(in); got != "" {
		t.Fatalf("CleanPrompt = %q, want empty", got)
	}
}

func TestCleanPromptKeepsCustomElementsInProse(t *testing.T) {
	// The unknown-block stripper only fires at the very start of a prompt, so
	// markup discussed mid-sentence survives.
	in := "the layout breaks when <my-widget> is nested"
	if got := CleanPrompt(in); got != in {
		t.Fatalf("CleanPrompt rewrote prose: %q", got)
	}
}

func TestExtractSkillRefs(t *testing.T) {
	refs, cleaned := ExtractSkillRefs("read ${HOME}/.claude/skills/storefront-verify/SKILL.md then run it")
	if len(refs) != 1 || refs[0] != "storefront-verify" {
		t.Fatalf("refs = %v", refs)
	}
	if strings.Contains(cleaned, "skills") || strings.Contains(cleaned, "claude") {
		t.Fatalf("cleaned still names the path: %q", cleaned)
	}
}

